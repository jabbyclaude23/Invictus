async page => {
  const base = 'http://127.0.0.1:4174';
  const checks = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 375, height: 844 });
  await page.goto(base);
  await page.evaluate(() => window.__fixture.reset());
  await page.reload();
  await page.getByRole('textbox', {name:'Priority 1',exact:true}).waitFor();
  const order = await page.evaluate(() => {
    const top = selector => document.querySelector(selector).getBoundingClientRect().top + scrollY;
    return top('.dashboard-topline') < top('#daily-focus') && top('.dashboard-goals') > top('.dashboard-columns');
  });
  if (!order) throw new Error('Quote/schedule and Goals order is incorrect');
  checks.push('Quote and schedule precede focus; narrative Goals follow the main dashboard');
  await page.getByRole('textbox', {name:'Priority 1',exact:true}).fill('Finish a meaningful project');
  await page.evaluate(() => {window.__fixture.failWrites = true;});
  await page.getByRole('button',{name:'Save priorities',exact:true}).click();
  await page.getByText('Your daily plan could not be saved. Please try again.',{exact:true}).waitFor();
  await page.evaluate(() => {window.__fixture.failWrites = false;});
  await page.getByRole('button',{name:'Save priorities',exact:true}).click();
  await page.getByText('Priorities saved',{exact:true}).waitFor();
  await page.getByRole('checkbox',{name:'Complete priority 1: Finish a meaningful project',exact:true}).check();
  await page.getByRole('spinbutton',{name:'Sleep hours last night'}).fill('7.5');
  await page.getByRole('spinbutton',{name:'Focused work minutes today'}).fill('135');
  await page.getByRole('radio',{name:'Energy 4: Good',exact:true}).check();
  await page.getByRole('textbox',{name:'Daily reflection'}).fill('Protecting a morning block helped.');
  await page.getByRole('button',{name:'Save check-in',exact:true}).click();
  await page.getByText('Check-in saved',{exact:true}).waitFor();
  await page.reload();
  await page.getByRole('textbox',{name:'Priority 1',exact:true}).waitFor();
  if (await page.getByRole('spinbutton',{name:'Focused work minutes today'}).inputValue() !== '135') throw new Error('Check-in did not persist');
  if (!await page.getByRole('checkbox',{name:'Complete priority 1: Finish a meaningful project',exact:true}).isChecked()) throw new Error('Priority completion did not persist');
  checks.push('Priorities and check-in persist, completion saves, and failed write can retry');
  await page.goto(`${base}/coach`);
  await page.evaluate(() => {window.__fixture.failReads = true;});
  await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:'Dashboard',exact:true}).click();
  await page.getByText('Your daily plan could not be loaded. Try again.',{exact:true}).waitFor();
  if (!await page.getByRole('button',{name:'Save priorities',exact:true}).isDisabled()) throw new Error('Unknown record could be overwritten after failed read');
  await page.evaluate(() => {window.__fixture.failReads = false;});
  await page.getByText('Your daily plan could not be loaded. Try again.',{exact:true}).locator('..').getByRole('button',{name:'Try again',exact:true}).click();
  await page.getByRole('button',{name:'Save priorities',exact:true}).waitFor();
  await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Save priorities')?.disabled);
  checks.push('Failed daily-plan reads block saving until retry loads the existing record');
  await page.goto(`${base}/workout`);
  await page.locator('.weekly-grid button[aria-expanded]').first().click();
  await page.getByRole('img',{name:'No verified demonstration available for Dumbbell Bench Press',exact:true}).waitFor();
  const mini = await page.getByRole('img',{name:'No verified demonstration available for Dumbbell Bench Press',exact:true}).boundingBox();
  if (!mini || mini.width < 50 || mini.width > 60) throw new Error('Mini exercise preview missing');
  await page.getByRole('img',{name:'No verified demonstration available for Plank',exact:true}).waitFor();
  checks.push('Expanded weekly exercises show compact previews and honest unavailable media states');
  await page.goto(`${base}/workout?empty=1`);
  await page.evaluate(() => window.__fixture.reset({empty:true}));
  await page.reload();
  await page.getByRole('spinbutton',{name:'How old are you? years'}).fill('29');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.getByRole('spinbutton',{name:"What's your current weight? lbs"}).fill('180');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.getByRole('spinbutton',{name:"What's your height? cm"}).fill('178');
  await page.getByRole('button',{name:'Next',exact:true}).click();
  for (const value of ['Male','Intermediate (1–3 years)','Build Muscle','4 days','60 minutes','Gym','Dumbbells']) {
    await page.getByRole('button',{name:value,exact:true}).click();
    await page.getByRole('button',{name:'Next',exact:true}).click();
  }
  await page.getByRole('heading',{name:'Any areas you want to focus on?'}).waitFor();
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.getByRole('heading',{name:'Any injuries or movements to avoid?'}).waitFor();
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.getByRole('button',{name:'8 weeks',exact:true}).click();
  await page.getByRole('button',{name:'Generate My Plan',exact:true}).click();
  await page.getByRole('heading',{level:1,name:'Strength & consistency'}).waitFor();
  const profile = await page.evaluate(() => Object.entries(window.__fixture.dump()).find(([key])=>key.endsWith('/profile/info'))?.[1]);
  if (!profile || profile.weightLbs !== 180 || Math.abs(profile.weight - 81.6466266) > .0001 || profile.weight_display !== '180 lbs') throw new Error(`Pounds profile incorrect: ${JSON.stringify(profile)}`);
  checks.push('Full workout setup asks for pounds and converts once to canonical kg for calculations');
  await page.goto(base);
  await page.evaluate(() => window.__fixture.reset());
  await page.reload();
  await page.getByRole('textbox',{name:'Priority 1',exact:true}).waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({path:'docs/previews/dashboard-updated-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1050});
  await page.screenshot({path:'docs/previews/dashboard-updated-desktop.png',fullPage:true});
  if (errors.length) throw new Error(errors.join('; '));
  return {passed:checks.length,checks,runtimeErrors:errors};
}

